// build.cjs — une los fotogramas y la musica en el video final.
// Orden completo:
//   npm run dev                (en otra terminal; la app en el puerto 5173)
//   node promo/clips.cjs       (graba los clips de la app)
//   node promo/render.cjs      (dibuja los 1800 fotogramas)
//   node promo/music.cjs       (crea la musica)
//   node promo/build.cjs       -> promo/out/marswalk-gale-promo.mp4
// Version de 30 s: SOLO=helmet30 en clips.cjs y DUR=30 delante de render.cjs, music.cjs y build.cjs
const { execFileSync } = require('child_process');
const path = require('path');
const ff = require('ffmpeg-static');

const D = __dirname;
const S = process.env.DUR === '30';                          // DUR=30 -> version corta de 30 s
const out = path.join(D, 'out', S ? 'marswalk-gale-promo-30s.mp4' : 'marswalk-gale-promo.mp4');
// Marca de agua obligatoria (reglas de NASA Space Apps): el video se hizo con ayuda de IA (SI)
const marca = "drawtext=fontfile='C\\:/Windows/Fonts/arialbd.ttf':text='AI-assisted (SI) · made with Claude':" +
  'fontsize=26:fontcolor=white@0.85:box=1:boxcolor=black@0.45:boxborderw=10:x=w-tw-40:y=h-th-36';
const nota = 'AI-assisted (SI): video, graphics and music generated by scripts written with the AI assistant Claude (Anthropic). ' +
  'App footage and data are real NASA data (MRO HiRISE, Mars Odyssey THEMIS, Curiosity, DONKI).';
execFileSync(ff, ['-y', '-loglevel', 'error', '-framerate', '30', '-i', path.join(D, S ? 'frames30' : 'frames', 'f%05d.jpg'),
  '-i', path.join(D, 'out', S ? 'music-30s.wav' : 'music.wav'),
  '-vf', marca, '-metadata', 'title=Marswalk Gale', '-metadata', 'comment=' + nota, '-metadata', 'description=' + nota,
  '-metadata:s:a:0', 'comment=AI-generated music (SI): synthesized by a script written with Claude.',
  '-c:v', 'libx264', '-preset', 'slow', '-crf', '18', '-pix_fmt', 'yuv420p', '-movflags', '+faststart',
  '-c:a', 'aac', '-b:a', '192k', '-shortest', out], { stdio: 'inherit' });
console.log('Video listo:', out);
